def generate_synthetic_production_records(
    days: int = 14,
    seed: int = 42
) -> List[Dict[str, Any]]:
    """
    Generates synthetic daily shift production records for the factory fleet.
    Guarantees deterministic, reproducible numbers using seed.
    """
    rng = random.Random(seed)
    records: List[Dict[str, Any]] = []
    base_date = datetime.now() - timedelta(days=days)

    for day_idx in range(days):
        current_date = (base_date + timedelta(days=day_idx)).strftime("%Y-%m-%d")

        for mach in FACTORY_MACHINES:
            m_id = mach["machine_id"]
            m_name = mach["machine_name"]
            cycle_sec = mach["ideal_cycle_sec"]

            # 3 shifts per day (8 hours each = 24h total planned per day)
            for shift_num in [1, 2, 3]:
                planned_hours = 8.0

                # Introduce realistic machine behavior profiles:
                # MAC-001: High performer (~91% OEE)
                # MAC-003: Moderate performer (~78% OEE)
                # MAC-004: Problematic asset (~61% OEE, low availability)
                # MAC-005: Low quality asset (~72% OEE, high scrap)
                if m_id == "MAC-004":
                    # Severe downtime asset
                    downtime = rng.uniform(1.8, 3.5)
                    operating_hours = max(0.5, planned_hours - downtime)
                    speed_factor = rng.uniform(0.75, 0.88)
                    quality_factor = rng.uniform(0.92, 0.96)
                elif m_id == "MAC-005":
                    # High scrap asset
                    downtime = rng.uniform(0.4, 1.2)
                    operating_hours = planned_hours - downtime
                    speed_factor = rng.uniform(0.88, 0.94)
                    quality_factor = rng.uniform(0.85, 0.91) # Low quality!
                elif m_id == "MAC-001":
                    # Star performer
                    downtime = rng.uniform(0.1, 0.6)
                    operating_hours = planned_hours - downtime
                    speed_factor = rng.uniform(0.93, 0.98)
                    quality_factor = rng.uniform(0.98, 0.995)
                else:
                    # Typical industrial asset
                    downtime = rng.uniform(0.3, 1.4)
                    operating_hours = planned_hours - downtime
                    speed_factor = rng.uniform(0.85, 0.95)
                    quality_factor = rng.uniform(0.95, 0.99)

                # Total theoretical units possible in operating time
                max_units = int((operating_hours * 3600.0) / cycle_sec)
                total_units = int(max_units * speed_factor)
                good_units = int(total_units * quality_factor)
                rejected_units = max(0, total_units - good_units)

                records.append({
                    "machine_id": m_id,
                    "machine_name": m_name,
                    "line": mach["line"],
                    "date": current_date,
                    "shift": f"Shift {shift_num}",
                    "planned_time_hours": planned_hours,
                    "operating_time_hours": round(operating_hours, 2),
                    "ideal_cycle_time_seconds": cycle_sec,
                    "total_units": total_units,
                    "good_units": good_units,
                    "rejected_units": rejected_units,
                    "is_synthetic": True,
                    "dataset_source": "PredictX Synthetic Manufacturing Generator (Demonstration Data)",
                })

    return records


def generate_synthetic_downtime_records(
    days: int = 14,
    seed: int = 42
) -> List[Dict[str, Any]]:
    """
    Generates synthetic stoppage events correlated with machines.
    """
    rng = random.Random(seed)
    downtime_events: List[Dict[str, Any]] = []
    base_date = datetime.now() - timedelta(days=days)

    for day_idx in range(days):
        current_dt = base_date + timedelta(days=day_idx)
        date_str = current_dt.strftime("%Y-%m-%d")

        for mach in FACTORY_MACHINES:
            m_id = mach["machine_id"]
            m_name = mach["machine_name"]

            # Probability of stoppage event on any given day
            prob = 0.70 if m_id == "MAC-004" else (0.45 if m_id in ("MAC-003", "MAC-005") else 0.20)
            if rng.random() < prob:
                cat, reason, hourly_rate = rng.choice(DOWNTIME_CATEGORIES)
                duration = round(rng.uniform(0.8, 3.8), 2)
                cost = round(duration * hourly_rate, 2)

                downtime_events.append({
                    "incident_id": f"DT-{date_str}-{m_id}-{len(downtime_events)+1:03d}",
                    "machine_id": m_id,
                    "machine_name": m_name,
                    "category": cat,
                    "reason": reason,
                    "duration_hours": duration,
                    "cost_impact": cost,
                    "timestamp": f"{date_str}T{rng.randint(8, 20):02d}:30:00Z",
                    "is_synthetic": True,
                    "dataset_source": "PredictX Synthetic Manufacturing Generator (Demonstration Data)",
                })

    return downtime_events


def generate_synthetic_failures_and_repairs(
    days: int = 14,
    seed: int = 42
) -> Dict[str, List[Dict[str, Any]]]:
    """
    Generates synthetic failure and repair completion records for MTBF/MTTR.
    """
    rng = random.Random(seed)
    failures: List[Dict[str, Any]] = []
    repairs: List[Dict[str, Any]] = []
    base_date = datetime.now() - timedelta(days=days)

    for day_idx in range(days):
        current_dt = base_date + timedelta(days=day_idx)
        date_str = current_dt.strftime("%Y-%m-%d")

        for mach in FACTORY_MACHINES:
            m_id = mach["machine_id"]
            m_name = mach["machine_name"]

            # Failure incidence rates
            failure_prob = 0.35 if m_id == "MAC-004" else (0.20 if m_id in ("MAC-002", "MAC-007") else 0.05)
            if rng.random() < failure_prob:
                f_id = f"FAIL-{date_str}-{m_id}-{len(failures)+1:03d}"
                cat, reason, _ = rng.choice(DOWNTIME_CATEGORIES)

                # MAC-004 has prolonged repair times (high MTTR)
                repair_duration = round(rng.uniform(3.5, 6.2) if m_id == "MAC-004" else rng.uniform(1.0, 2.8), 2)

                failures.append({
                    "failure_id": f_id,
                    "machine_id": m_id,
                    "machine_name": m_name,
                    "failure_type": cat,
                    "root_cause": reason,
                    "timestamp": f"{date_str}T10:15:00Z",
                    "is_synthetic": True,
                    "dataset_source": "PredictX Synthetic Manufacturing Generator (Demonstration Data)",
                })

                repairs.append({
                    "repair_id": f"REP-{f_id}",
                    "failure_id": f_id,
                    "machine_id": m_id,
                    "machine_name": m_name,
                    "repair_duration_hours": repair_duration,
                    "technician": f"Tech-{rng.randint(101, 108)}",
                    "status": "COMPLETED",
                    "timestamp": f"{date_str}T14:45:00Z",
                    "is_synthetic": True,
                    "dataset_source": "PredictX Synthetic Manufacturing Generator (Demonstration Data)",
                })

    return {"failures": failures, "repairs": repairs}


class DemonstrationDataset:
    """
    In-memory demonstration dataset container.
    Provides uniform accessors for development and fallback when database is empty.
    """
    def __init__(self, days: int = 14, seed: int = 42):
        self.production_records = generate_synthetic_production_records(days=days, seed=seed)
        self.downtime_records = generate_synthetic_downtime_records(days=days, seed=seed)
        res = generate_synthetic_failures_and_repairs(days=days, seed=seed)
        self.failure_records = res["failures"]
        self.repair_records = res["repairs"]
        self.machines = FACTORY_MACHINES


# Global pre-instantiated singleton for zero-overhead demonstration
